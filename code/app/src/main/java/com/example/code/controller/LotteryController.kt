    /**
     * Publishes one lottery for selected campsites owned by the current owner.
     * Identity and names come from the supplied campsite records, not form fields.
     */
    suspend fun publishLottery(
        repository: LotteryCreationRepository,
        campsites: List<Campsite>,
        ownerId: String,
        settings: Lottery,
    ): String {
        require(campsites.isNotEmpty()) { "Select at least one campsite." }
        require(ownerId.isNotBlank() && campsites.all { it.ownerId == ownerId }) {
            "You can only create lotteries for your own campsites."
        }
        require(campsites.map { it.id }.distinct().size == campsites.size) {
            "A campsite cannot be selected more than once."
        }

        val first = campsites.first()
        val references = campsites.map { LotteryCampsite(id = it.id, name = it.name) }
        val lottery = settings.copy(
            id = "",
            campsiteId = first.id,
            campsiteName = first.name,
            ownerId = ownerId,
            campsites = if (references.size > 1) references else emptyList(),
            waitingListCount = 0,
            status = Lottery.STATUS_OPEN,
            winnerIds = emptyList(),
        )
        validateCreation(lottery)
        return repository.createLottery(lottery)
    }

    /** Resolves both new shared lotteries and existing single-campsite documents. */
    fun includedCampsites(lottery: Lottery): List<LotteryCampsite> =
        lottery.campsites.ifEmpty {
            listOf(LotteryCampsite(id = lottery.campsiteId, name = lottery.campsiteName))
        }

    fun includesCampsite(lottery: Lottery, campsiteId: String): Boolean =
        campsiteId.isNotBlank() && includedCampsites(lottery).any { it.id == campsiteId }

    fun campsiteSummary(lottery: Lottery): String =
        includedCampsites(lottery).joinToString(", ") { it.name }
    // === US 02.04.02: END owner publication and legacy compatibility ===

    /** Shared form/persistence validation. Throws with a message for the owner. */
    // === US 02.04.02: BEGIN validate all selected campsites ===
    fun validateCreation(lottery: Lottery) {
        val selected = includedCampsites(lottery)
        require(selected.all {
            it.id.isNotBlank() && '/' !in it.id && it.id != "." && it.id != ".."
        }) { "A saved campsite is required." }
        require(selected.all { it.name.isNotBlank() }) { "The campsite needs a name." }
        require(selected.map { it.id }.distinct().size == selected.size) {
            "A campsite cannot be selected more than once."
        }
        require(
            lottery.campsiteId == selected.first().id &&
                    lottery.campsiteName == selected.first().name,
        ) { "The lottery's campsite information is inconsistent." }
        require(lottery.ownerId.isNotBlank()) { "An owner ID is required." }
        require(lottery.registrationStart < lottery.registrationEnd) {
            "Registration must start before it ends."
        }
        require(lottery.registrationEnd <= lottery.bookingStart) {
            "Registration must end on or before the booking period starts."
        }
        require(lottery.bookingStart < lottery.bookingEnd) {
            "The booking period must start before it ends."
        }
        require(lottery.winnerCount >= 1) { "Choose at least one winner." }
        require(lottery.waitlistCapacity == null || lottery.waitlistCapacity >= lottery.winnerCount) {
            "Waiting-list capacity must be at least the number of winners, or left blank."
        }
    }
    // === US 02.04.02: END validate all selected campsites ===

    /**
     * Returns true if entrants can join or leave the waiting list of
     * [lottery] at [now]: it is not drawn and [now] is inside the
     * registration period.
     */
    fun isRegistrationOpen(lottery: Lottery, now: Long): Boolean =
        lottery.status == Lottery.STATUS_OPEN &&
                now in lottery.registrationStart until lottery.registrationEnd

    /** Returns true if the waiting list of [lottery] has room for one more entrant. */
    fun hasRoom(lottery: Lottery): Boolean =
        lottery.waitlistCapacity == null || lottery.waitingListCount < lottery.waitlistCapacity

    /**
     * Returns the name shown for [entry], falling back to a short device ID
     * when the entrant has no name.
     */
    fun entrantDisplayName(entry: WaitingListEntry): String =
        entry.entrantName.ifBlank { "Entrant ${entry.entrantId.take(6)}" }
}
