/**
 * Entrant's Reservations tab.
 *
 * @param reservations all reservations.
 * @param deviceId this entrant's ID.
 * @param controller reservation controller, used to cancel (US 01.07.01); null hides Cancel.
 */
@Composable
fun EntrantReservationsRoute(
    reservations: List<Reservation>,
    deviceId: String,
    controller: ReservationController? = null,
) {
    val scope = rememberCoroutineScope()
    var cancelMessage by remember { mutableStateOf<String?>(null) }
    val now = System.currentTimeMillis()
    EntrantReservationsScreen(
        reservations = ReservationController.activeForEntrant(reservations, deviceId, now),
        pastReservations = com.example.code.controller.pastReservationsForEntrant(reservations, deviceId, now),
        statusMessage = cancelMessage,
        onCancel = controller?.let { c ->
            { reservation ->
                scope.launch {
                    cancelMessage = try {
                        c.cancel(reservation, deviceId)
                        "Reservation for ${reservation.campsiteName} cancelled."
                    } catch (e: Exception) {
                        "Could not cancel: ${e.message}"
                    }
                }
            }
        },
    )
}

/**
 * Owner's Reservations tab.
 *
 * @param reservations all reservations.
 * @param deviceId this owner's ID.
 * @param controller reservation controller.
 */
@Composable
fun OwnerReservationsRoute(
    reservations: List<Reservation>,
    deviceId: String,
    controller: ReservationController,
    onMessage: ((Reservation) -> Unit)? = null,
) {
    val scope = rememberCoroutineScope()
    var message by remember { mutableStateOf<String?>(null) }
    val now = System.currentTimeMillis()

    OwnerReservationsScreen(
        bookedDates = ReservationController.bookedDates(reservations, deviceId, now),
        reservations = ReservationController.activeForOwner(reservations, deviceId, now),
        onMessage = onMessage,
        pastReservations = com.example.code.controller.pastReservationsForOwner(reservations, deviceId, now),
        cancelledReservations = com.example.code.controller.cancelledReservationsForOwner(reservations, deviceId),
        statusMessage = message,
        onReject = { reservation, reason ->
            scope.launch {
                message = try {
                    controller.reject(reservation, reason)
                    "Reservation for ${reservation.campsiteName} rejected."
                } catch (e: Exception) {
                    "Could not reject: ${e.message}"
                }
            }
        },
    )
}
