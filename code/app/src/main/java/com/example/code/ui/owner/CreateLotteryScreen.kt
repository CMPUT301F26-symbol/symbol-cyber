/** Native pickers avoid requiring an additional date library or Material opt-in. */
@Composable
private fun LotteryDateTimeField(
    label: String,
    value: Long?,
    enabled: Boolean,
    onSelected: (Long) -> Unit,
) {
    val context = LocalContext.current
    var dialog by remember { mutableStateOf<Dialog?>(null) }
    var error by remember { mutableStateOf<String?>(null) }
    DisposableEffect(Unit) {
        onDispose { dialog?.dismiss() }
    }
    OutlinedTextField(
        value = value?.let(::formatDateTime).orEmpty(),
        onValueChange = {},
        label = { Text(label) },
        readOnly = true,
        enabled = enabled,
        modifier = Modifier.fillMaxWidth(),
        trailingIcon = {
            TextButton(
                enabled = enabled,
                onClick = {
                    val initial = Calendar.getInstance().apply {
                        if (value != null) timeInMillis = value
                    }
                    val dateDialog = DatePickerDialog(
                        context,
                        { _, year, month, day ->
                            val timeDialog = TimePickerDialog(
                                context,
                                { _, hour, minute ->
                                    val selected = Calendar.getInstance().apply {
                                        isLenient = false
                                        clear()
                                        set(year, month, day, hour, minute, 0)
                                    }
                                    try {
                                        onSelected(selected.timeInMillis)
                                        error = null
                                    } catch (e: IllegalArgumentException) {
                                        error = "That local time does not exist. Choose another time."
                                    }
                                },
                                initial.get(Calendar.HOUR_OF_DAY),
                                initial.get(Calendar.MINUTE),
                                DateFormat.is24HourFormat(context),
                            )
                            timeDialog.setTitle(label)
                            dialog = timeDialog
                            timeDialog.show()
                        },
                        initial.get(Calendar.YEAR),
                        initial.get(Calendar.MONTH),
                        initial.get(Calendar.DAY_OF_MONTH),
                    )
                    dateDialog.setTitle(label)
                    dialog = dateDialog
                    dateDialog.show()
                },
            ) { Text("Choose") }
        },
    )
    error?.let { Text(it, color = MaterialTheme.colorScheme.error) }
}
